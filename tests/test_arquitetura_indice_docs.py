"""scripts/arquitetura/indice_docs.py: docs/INDEX.md is generated from the C4 model and the
front matter of the transversal docs, and `conferir` fails when it differs or a doc is left out
(df-8x0m.23.39.2)."""

import subprocess
import sys
from pathlib import Path

import pytest

from scripts.arquitetura import indice_docs, modelo

ROOT = Path(__file__).resolve().parents[1]
BOX = "---\ntopic: Engine\nread_when: When working on the engine\ncode: []\nstatus: pronto\n---\n"
TRANSVERSAL = "---\ntopic: Commands\nread_when: When running a command\ntransversal: true\n---\n"


def _element(id_, kind, title, doc=None):
    links = [{"url": f"../{doc}", "title": "doc"}] if doc else []
    return {"id": id_, "kind": kind, "title": title, "links": links}


@pytest.fixture
def repo(tmp_path, monkeypatch):
    monkeypatch.setattr(indice_docs, "ADRS", {"docs/adr/0001-x.md": ("History", "Background only")})
    (tmp_path / "docs" / "adr").mkdir(parents=True)
    (tmp_path / "docs" / "engine.md").write_text(BOX, encoding="utf-8")
    (tmp_path / "docs" / "commands.md").write_text(TRANSVERSAL, encoding="utf-8")
    (tmp_path / "docs" / "adr" / "0001-x.md").write_text("# A frozen decision\n", encoding="utf-8")
    model = {"elements": [
        _element("casaHoje", "sistema", "Casa"),
        _element("casaHoje.motorHoje", "conteiner", "Motor", "docs/engine.md"),
        _element("casaAlvo.motorAlvo", "conteiner", "Motor", "docs/engine.md"),
        _element("casaAlvo.maquinaAlvo", "conteiner", "Máquina", "docs/engine.md"),
        _element("casaAlvo", "sistema", "Casa"),
        _element("lucas", "pessoa", "Pessoa", "docs/engine.md"),
    ]}
    (tmp_path / "docs" / "INDEX.md").write_text(indice_docs.gerar(model, tmp_path), encoding="utf-8")
    return tmp_path, model


def test_the_committed_index_is_the_generated_one():
    assert (ROOT / indice_docs.INDICE).read_text(encoding="utf-8") == indice_docs.gerar(modelo.load(), ROOT)


def test_conferir_passes_on_the_repo():
    run = subprocess.run([sys.executable, "-S", "scripts/arquitetura/indice_docs.py", "conferir"],
                         cwd=ROOT, capture_output=True, text=True, check=False)
    assert run.returncode == 0, run.stdout


def test_the_index_lists_each_part(repo):
    raiz, model = repo
    text = indice_docs.gerar(model, raiz)
    assert text.startswith(f"<!-- Generated by `{indice_docs.COMANDO}`")
    assert "### Casa" in text
    assert "#### Motor" in text
    assert f"### {indice_docs.FORA}" in text
    # today's and the target's boxes, even under another container id: one row, in today's table
    assert "| docs/engine.md | Máquina, Motor | When working on the engine |" in text
    assert "#### Máquina" not in text
    assert "| docs/commands.md | Commands | When running a command |" in text
    assert "| docs/adr/0001-x.md | History | Background only |" in text
    assert indice_docs.conferir(model, raiz) == []


def test_an_edited_line_fails(repo):
    raiz, model = repo
    index = raiz / "docs" / "INDEX.md"
    index.write_text(index.read_text(encoding="utf-8").replace("When running", "When typing"), encoding="utf-8")
    assert indice_docs.conferir(model, raiz) == [
        f"error: docs/INDEX.md is not the generated one: run {indice_docs.COMANDO}"]


def test_a_doc_in_no_part_fails(repo):
    raiz, model = repo
    (raiz / "docs" / "solto.md").write_text("---\ntopic: Solto\nread_when: never\n---\n", encoding="utf-8")
    problems = indice_docs.conferir(model, raiz)
    assert problems[0].startswith("error: docs/solto.md is in no part of the INDEX")


def test_history_is_not_a_doc_left_out(repo):
    raiz, model = repo
    (raiz / "docs" / "phases").mkdir()
    (raiz / "docs" / "phases" / "1.md").write_text("# old\n", encoding="utf-8")
    assert indice_docs.fora_do_indice(model, raiz) == []


def test_every_adr_has_its_read_when():
    assert sorted(indice_docs.ADRS) == sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "docs" / "adr").glob("*.md"))


def test_an_adr_not_in_adrs_fails(repo, monkeypatch):
    raiz, model = repo
    monkeypatch.setattr(indice_docs, "ADRS", {})
    assert indice_docs.fora_do_indice(model, raiz) == ["docs/adr/0001-x.md"]
